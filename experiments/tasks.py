#!/usr/bin/env python3
"""List, inspect, claim and render work items without creating remote issues."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PATH = ROOT / 'collaboration/work_items.json'
PLAN = ROOT / 'formalization/blueprint/tasks.json'


def render(items, nodes):
    lines = ['# Work queue', '', 'Generated by `python3 experiments/tasks.py render`. '
             'Read the [collaboration guide](../CONTRIBUTING.md) before claiming work.', '',
             '| Task | Kind | State | Owner | Registered component tests |',
             '|---|---|---|---|---|']
    for item in items:
        key = item['id']
        lines.append(f'| [{key}](tasks/{key}.md) | {item["kind"]} | {item["state"]} | '
                     f'{item["owner"] or "unassigned"} | {", ".join(item["contracts"]) or "none yet"} |')
    (ROOT / 'collaboration/TASKS.md').write_text('\n'.join(lines) + '\n')
    for item in items:
        node = nodes[item['id']]
        lines = [f'# {node["id"]}: {node["title"]}', '',
                 f'Kind: {item["kind"]}. State: {item["state"]}. '
                 f'Owner: {item["owner"] or "unassigned"}. Priority: P{node["priority"]}.', '',
                 '## Goal', '', node['contract'], '', '## Dependencies', '',
                 ', '.join(node['dependencies']) or 'No prerequisite task.', '',
                 'These are mathematical dependencies. Specification work may inspect '
                 'available source before the prerequisite is fully certified.', '',
                 '## Starting evidence', '']
        lines += [f'- [{path}](../../{path})' for path in node['evidence']]
        lines += ['', '## Deliverable and acceptance', '', item['deliverable'], '',
                  'Registered component contracts: ' + (', '.join(item['contracts']) or 'none yet') + '.', '',
                  'A component test does not close its parent theorem. For an implementation PR, '
                  'first provide a reviewed concrete specification and register its typed binding '
                  'and axiom test. No hypothetical proposition fields or admitted theorem may '
                  'stand in for a missing PDE statement.', '',
                  'Run `make check`; for Lean implementation work also run `make test` and '
                  '`make test-mutations`. Include the task ID and exact commands in the PR.']
        (ROOT / f'collaboration/tasks/{node["id"]}.md').write_text('\n'.join(lines) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['list', 'show', 'claim', 'render'])
    parser.add_argument('task', nargs='?')
    parser.add_argument('owner', nargs='?')
    parser.add_argument('--ready', action='store_true')
    args = parser.parse_args()
    data = json.loads(PATH.read_text())
    nodes = {n['id']: n for n in json.loads(PLAN.read_text())['nodes']}
    items = {x['id']: x for x in data['items']}
    assert set(items) == set(nodes), 'Queue and mathematical task graph differ'
    if args.command == 'render':
        render(data['items'], nodes)
    elif args.command == 'list':
        for x in data['items']:
            if not args.ready or x['state'] == 'ready':
                print(f'{x["id"]:5} {x["kind"]:15} {x["state"]:20} {x["owner"] or "unassigned"}')
    else:
        assert args.task in items, 'Unknown task ID'
        if args.command == 'show':
            print((ROOT / f'collaboration/tasks/{args.task}.md').read_text())
        else:
            assert args.owner in data['collaborators'], 'Unknown collaborator'
            item = items[args.task]
            assert item['owner'] in [None, args.owner], 'Task is already claimed by another collaborator'
            item['owner'] = args.owner
            item['state'] = 'in-progress'
            PATH.write_text(json.dumps(data, indent=2) + '\n')
            render(data['items'], nodes)
            print('Commit this claim in a short PR before starting overlapping work.')


if __name__ == '__main__':
    main()
